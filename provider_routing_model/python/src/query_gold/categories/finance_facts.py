"""Curated finance facts backed by pinned public issuer earnings releases."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class FinanceFact:
    """One direct, source-supported answer-bearing search question."""

    case_id: str
    source_record_id: str
    query: str
    question_type: str
    answer: str
    value: float | list[float]
    units: str
    field_token: str
    value_token: str
    unit_token: str
    period_token: str
    anchor: str
    context_before: int = 0
    context_after: int = 0
    column_index: int | None = None
    currency: str | None = "USD"


def _fact(
    case_id: str,
    source_record_id: str,
    query: str,
    question_type: str,
    answer: str,
    value: float | list[float],
    units: str,
    field_token: str,
    value_token: str,
    unit_token: str,
    period_token: str,
    anchor: str,
    *,
    context_before: int = 0,
    context_after: int = 0,
    column_index: int | None = None,
    currency: str | None = "USD",
) -> FinanceFact:
    return FinanceFact(
        case_id=case_id,
        source_record_id=source_record_id,
        query=query,
        question_type=question_type,
        answer=answer,
        value=value,
        units=units,
        field_token=field_token,
        value_token=value_token,
        unit_token=unit_token,
        period_token=period_token,
        anchor=anchor,
        context_before=context_before,
        context_after=context_after,
        column_index=column_index,
        currency=currency,
    )


